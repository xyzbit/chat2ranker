export function createTranslator(locale) {
  const dictionary = messages[locale] || messages.zh;
  return (key, values = {}) => Object.entries(values).reduce(
    (value, [name, replacement]) => value.replaceAll(`{${name}}`, String(replacement)),
    dictionary[key] || managementCopy[key]?.[locale === "en" ? 1 : 0] || key,
  );
}

export function formatDateTime(locale, value) {
  if (!value) return "—";
  return new Intl.DateTimeFormat(locale === "en" ? "en-US" : "zh-CN", {
    month: "short",
    day: "numeric",
    year: locale === "en" ? "numeric" : undefined,
    hour: "2-digit",
    minute: "2-digit",
  }).format(new Date(value));
}

export function initialLocale() {
  const stored = globalThis.localStorage?.getItem("rank.locale");
  if (stored === "zh" || stored === "en") return stored;
  return globalThis.navigator?.language?.toLowerCase().startsWith("en") ? "en" : "zh";
}
