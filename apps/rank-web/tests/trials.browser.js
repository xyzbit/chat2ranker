async (page) => {
  const check = (value, message) => { if (!value) throw new Error(message); };
  const origin = await page.evaluate(() => location.origin);
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.evaluate(() => { localStorage.setItem("rank.modelSetupDismissed", "true"); localStorage.setItem("rank.locale", "zh"); });
  await page.reload();
  const select = async (name, option) => {
    await page.getByRole("combobox", { name, exact: true }).click();
    await page.getByRole("option", { name: option, exact: true }).click();
  };
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 900 });
    await page.goto(`${origin}/#/agents`);
    await page.getByRole("button", { name: /Trial Agent.*@test\/trial/ }).click();
    await select("版本", /v1/);
    check(await page.getByRole("heading", { name: "工具与 Skill", exact: true }).isVisible(), "Agent resources are collapsed");
    await page.getByRole("link", { name: "版本对比", exact: true }).click();
    await page.getByRole("heading", { name: "版本对比", exact: true }).waitFor();
    check(page.url().includes("compare=1"), "Version comparison has no addressable page");
    await page.reload();
    await page.getByRole("combobox", { name: "基准版本", exact: true }).waitFor();
    await page.getByRole("link", { name: "Trial Agent", exact: true }).click();
    const configTab = page.getByRole("tab", { name: "配置", exact: true });
    const evaluationTab = page.getByRole("tab", { name: "评测", exact: true });
    check(await configTab.getAttribute("aria-selected") === "true", "Agent did not open its configuration");
    check(!await page.getByRole("heading", { name: "评测配置", exact: true }).isVisible(), "Evaluation settings leaked into configuration");
    await configTab.focus();
    await page.keyboard.press("ArrowRight");
    await page.getByRole("heading", { name: "评测配置", exact: true }).waitFor();
    check(!await page.getByRole("button", { name: "创建新版本", exact: true }).isVisible(), "Version creation leaked into evaluation settings");
    const development = page.getByRole("combobox", { name: "开发评测集", exact: true });
    await development.click();
    const datasetOption = page.getByRole("option").filter({ hasNotText: "未设置" }).first();
    const datasetName = await datasetOption.innerText();
    await datasetOption.click();
    await configTab.click();
    await evaluationTab.click();
    check((await development.innerText()).includes(datasetName), "Switching tabs lost unsaved evaluation settings");
    await page.locator(".agent-defaults").getByRole("button", { name: "保存", exact: true }).click();
    await page.locator(".agent-defaults").getByRole("status").getByText("已保存", { exact: true }).waitFor();
    await page.reload();
    await evaluationTab.click();
    await page.waitForFunction(name => document.querySelector(".agent-defaults .ui-select")?.textContent.includes(name), datasetName);
    await select("版本", "v2");
    check((await development.innerText()).includes(datasetName), "Agent versions do not share evaluation defaults");
    check(await evaluationTab.getAttribute("aria-selected") === "true", "Changing versions left evaluation");
    await page.getByRole("combobox", { name: "版本", exact: true }).click();
    check(await page.getByRole("option").count() === 2, "Saving evaluation settings created an Agent version");
    await page.getByRole("option", { name: "v1", exact: true }).click();
    await page.screenshot({ path: `output/playwright/agent-evaluation-tab-${width}.png`, fullPage: true });
    await evaluationTab.focus();
    await page.keyboard.press("ArrowLeft");
    await page.getByRole("button", { name: "创建新版本", exact: true }).waitFor();
    await page.getByRole("button", { name: "对话试用", exact: true }).click();
    const trial = page.locator(".trial-page");
    await trial.getByText("Trial Agent · v1", { exact: true }).first().waitFor();
    await trial.getByRole("button", { name: "新建试用", exact: true }).click();
    check(await trial.getByRole("textbox", { name: "和 Agent 对话…" }).isEnabled(), "Agent handoff did not enable composer");
    check(!page.url().includes("/trials"), "Trial still uses a standalone page");
    check(await page.getByRole("navigation", { name: width > 640 ? "页面" : "主导航", exact: true }).getByRole("button", { name: "Agent 试用", exact: true }).count() === 0, "Standalone trial navigation remains");
    await trial.getByTitle("查看配置", { exact: true }).click();
    const configuration = page.getByRole("dialog", { name: "查看配置", exact: true });
    await configuration.getByText("Trial system prompt", { exact: true }).waitFor();
    await page.keyboard.press("Escape");
    check(await trial.isVisible(), "Escape closed the dock instead of the configuration dialog");
    await configuration.waitFor({ state: "hidden" });
    await page.screenshot({ path: `output/playwright/trial-start-${width}.png`, fullPage: true });
    if (width > 1100) {
      const context = await page.locator(".workspace-context > .management-page").boundingBox();
      const chat = await trial.boundingBox();
      check(context.x + context.width <= chat.x + 1, "Trial covers desktop Agent configuration");
    }
    const send = async text => {
      await trial.getByRole("textbox", { name: "和 Agent 对话…" }).fill(text);
      await trial.getByRole("button", { name: "发送消息", exact: true }).click();
    };
    await send("Browser Ada");
    await trial.getByText("Reply: Browser Ada", { exact: true }).waitFor();
    await send("Who?");
    await trial.getByText("Reply: Who? | First: Browser Ada", { exact: true }).waitFor();
    check(await trial.locator(".trial-scroll").evaluate(node => getComputedStyle(node).scrollbarWidth === "none"), "Trial conversation has a visible scrollbar");
    const conversationURL = page.url();
    await page.reload();
    await trial.getByText("Reply: Who? | First: Browser Ada", { exact: true }).waitFor();
    check(await trial.locator(".trial-turn").count() === 2, "Reload duplicated turns");
    await trial.locator(".trial-scroll").evaluate(node => { node.style.height = "160px"; node.style.flex = "none"; node.scrollTop = 0; node.dispatchEvent(new Event("scroll")); });
    await page.waitForFunction(() => document.querySelector(".trial-scroll")?.dataset.scrollBottom === "true");
    check(await trial.locator(".trial-scroll").evaluate(node => getComputedStyle(node).maskImage !== "none" && node.dataset.scrollTop === "false"), "Trial overflow does not fade its lower edge");
    await trial.locator(".trial-scroll").evaluate(node => { node.scrollTop = node.scrollHeight; node.dispatchEvent(new Event("scroll")); });
    await page.waitForFunction(() => document.querySelector(".trial-scroll")?.dataset.scrollBottom === "false");
    await trial.locator(".trial-scroll").evaluate(node => { node.style.removeProperty("height"); node.style.removeProperty("flex"); });
    await trial.getByText("执行详情", { exact: true }).last().click();
    await page.screenshot({ path: `output/playwright/trial-chat-${width}.png`, fullPage: true });
    await send("slow");
    await trial.getByRole("button", { name: "停止", exact: true }).waitFor();
    await trial.getByRole("button", { name: "停止", exact: true }).click();
    await trial.getByText("已停止", { exact: true }).waitFor();
    await send("After stop");
    await trial.getByText("Reply: After stop | First: Browser Ada", { exact: true }).waitFor();
    await send("slow");
    await trial.getByRole("button", { name: "停止", exact: true }).waitFor();
    await page.locator(".dock-heading").getByRole("button", { name: "关闭", exact: true }).click();
    check(!await trial.isVisible(), "Close did not hide panel");
    await page.getByRole("button", { name: "对话试用", exact: true }).click();
    await trial.getByText("Reply: slow | First: Browser Ada", { exact: true }).waitFor();
    await trial.getByRole("textbox", { name: "和 Agent 对话…" }).fill("Unsent draft");
    await page.locator(".dock-heading").getByRole("button", { name: "关闭", exact: true }).click();
    await page.getByRole("button", { name: "对话试用", exact: true }).click();
    check(await trial.locator("textarea").inputValue() === "Unsent draft", "Close lost unsent draft");
    await page.getByRole("tab", { name: "Rank 助手", exact: true }).click();
    const rank = page.locator(".assistant-route");
    await rank.locator("#task-input").fill("Rank draft");
    check(!await trial.isVisible(), "Switching modes left two conversations visible");
    if (width > 1100) {
      const context = await page.locator(".workspace-context").boundingBox();
      const dock = await page.locator(".conversation-dock").boundingBox();
      check(context.x + context.width <= dock.x + 1, "Rank covers desktop configuration");
    }
    await page.screenshot({ path: `output/playwright/rank-dock-${width}.png`, fullPage: true });
    await page.getByRole("tab", { name: "试用", exact: true }).click();
    check(await trial.locator("textarea").inputValue() === "Unsent draft", "Mode switch lost trial draft");
    await page.getByRole("tab", { name: "Rank 助手", exact: true }).click();
    check(await rank.locator("#task-input").inputValue() === "Rank draft", "Mode switch lost Rank draft");
    await page.getByRole("tab", { name: "试用", exact: true }).click();
    await send("fail");
    await trial.getByRole("button", { name: "重试", exact: true }).waitFor();
    await trial.getByRole("button", { name: "重试", exact: true }).click();
    await trial.getByRole("button", { name: "重试", exact: true }).waitFor();
    if (width <= 1100) await page.locator(".dock-heading").getByRole("button", { name: "关闭", exact: true }).click();
    await select("版本", /v2/);
    if (width <= 1100) await page.getByRole("button", { name: "对话试用", exact: true }).click();
    await trial.getByTitle("查看配置", { exact: true }).filter({ hasText: "v2" }).waitFor();
    await trial.getByRole("button", { name: "新建试用", exact: true }).click();
    await send("New version");
    await trial.getByText("Reply: New version", { exact: true }).waitFor();
    await trial.getByRole("button", { name: "试用会话", exact: true }).click();
    await trial.locator(".trial-history").getByRole("button", { name: "Browser Ada Trial Agent · v1", exact: true }).first().click();
    await trial.getByText("Reply: Who? | First: Browser Ada", { exact: true }).waitFor();
    check(page.url() === conversationURL, "History did not restore selected conversation");
    await trial.getByRole("button", { name: "试用会话", exact: true }).click();
    check(!await trial.locator(".trial-history").innerText().then(text => text.includes("Native Trial")), "History leaked another Agent");
    await trial.locator(".trial-history").getByRole("button", { name: "关闭", exact: true }).click();
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Trial overflows horizontally");
    check(await trial.locator(".trial-composer").evaluate(el => { const r = el.getBoundingClientRect(); return r.bottom <= innerHeight && r.left >= 0 && r.right <= innerWidth; }), "Composer outside viewport");
    const conversationID = await page.evaluate(url => new URLSearchParams(url.split("?")[1]).get("conversation"), conversationURL);
    await page.goto(`${origin}/#/trials?conversation=${conversationID}`);
    await trial.getByText("Reply: Who? | First: Browser Ada", { exact: true }).waitFor();
    check(page.url().includes("#/agents?"), "Legacy trial link did not open Agent panel");
    await page.locator(".dock-heading").getByRole("button", { name: "关闭", exact: true }).click();
    await page.getByRole("button", { name: "Agent 资产", exact: true }).click();
    await page.getByRole("button", { name: /Native Trial.*@test\/native-trial/ }).click();
    await page.getByRole("button", { name: "对话试用", exact: true }).click();
    await trial.getByText("Native answer", { exact: true }).waitFor();
    check(!await trial.innerText().then(text => text.includes("Browser Ada")), "Agent switch reused another Agent's context");
  }
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(`${origin}/#/agents`);
  await page.getByRole("button", { name: /Trial Agent.*@test\/trial/ }).click();
  await page.getByRole("link", { name: "去发布", exact: true }).click();
  await page.getByRole("heading", { name: "trial-published", exact: true }).waitFor();
  await page.getByRole("link", { name: "全部端点", exact: true }).click();
  await page.locator(".deployment-list-row").filter({ hasText: "trial-published" }).waitFor();
  check(await page.locator(".deployment-heading").count() === 0, "Deployment navigation auto-selected a detail");
  await page.screenshot({ path: "output/playwright/deployment-list.png", fullPage: true });
  await page.goto(`${origin}/#/agents`);
  await page.getByRole("button", { name: /Trial Agent.*@test\/trial/ }).click();
  await select("版本", "v1");
  await page.getByRole("link", { name: "去发布", exact: true }).click();
  const creation = page.locator(".deployment-create-form");
  await creation.getByText("Trial Agent · v1", { exact: true }).waitFor();
  check(await creation.getByRole("combobox").count() === 0, "Publishing asks to choose the Agent again");
  check(!await creation.getByRole("spinbutton").first().isVisible(), "Advanced deployment controls are expanded");
  await creation.locator("summary").click();
  check(await creation.getByRole("checkbox").count() === 0, "Endpoint exposes redundant capability switches");
  await creation.locator("summary").click();
  await page.screenshot({ path: "output/playwright/agent-publish-create.png", fullPage: true });
  await creation.getByRole("button", { name: "取消", exact: true }).click();
  await page.getByRole("tab", { name: "评测", exact: true }).click();
  await page.getByRole("link", { name: "前往评测", exact: true }).click();
  await page.locator(".agent-route #task-input").waitFor();
  check(await page.locator("#task-input").inputValue() === "@test/trial 开始评测", "Evaluation handoff did not prefill a natural draft");
  check(await page.locator(".mention-chips").innerText().then(text => text.includes("@test/trial v1")), "Evaluation handoff lost the exact version");
  const evaluation = await page.evaluate(async () => {
    const id = localStorage.getItem("rank.activeExperiment");
    return fetch("/api/experiments/" + id).then(response => response.json());
  });
  check(evaluation.agent.version === 1 && evaluation.runs.length === 0 && evaluation.messages.every(item => item.role !== "user"), "Evaluation handoff executed or selected another version");
  await page.screenshot({ path: "output/playwright/agent-evaluation-draft.png", fullPage: true });
  await page.goto(`${origin}/#/agents`);
  await page.getByRole("button", { name: /Trial Agent.*@test\/trial/ }).click();
  await select("版本", "v1");
  await page.getByRole("link", { name: "去发布", exact: true }).click();
  await creation.getByRole("button", { name: "创建并继续", exact: true }).click();
  const release = page.getByRole("dialog", { name: "发布新版本", exact: true });
  await release.locator(".release-agent-target").getByText("Trial Agent v1", { exact: true }).waitFor();
  check(await release.getByRole("combobox", { name: "目标版本", exact: true }).count() === 0, "Creation asks to choose the version again");
  await release.getByRole("button", { name: "关闭", exact: true }).click();
  await page.goto(`${origin}/#/agent`);
  await page.getByRole("region", { name: "最近会话", exact: true }).getByRole("button", { name: "Control handoff", exact: true }).click();
  await page.getByRole("button", { name: "打开试用", exact: true }).click();
  await page.locator(".trial-page").getByRole("textbox", { name: "和 Agent 对话…" }).waitFor();
  check(await page.locator(".trial-page textarea").inputValue() === "Remember Ada", "Control handoff lost draft");
  check(await page.locator(".trial-turn").count() === 0, "Control handoff auto-executed input");
  await page.screenshot({ path: "output/playwright/trial-handoff.png", fullPage: true });
  await page.goto(`${origin}/#/deployments`);
  await page.locator(".deployment-list-row").filter({ hasText: "trial-published" }).click();
  check(await page.locator(".deployment-current").getByRole("button", { name: "打开试用", exact: true }).count() === 0, "Endpoint still exposes a trial button");
  check(errors.length === 0, errors.join("\n"));
}
