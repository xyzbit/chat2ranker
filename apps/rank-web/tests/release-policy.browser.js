async (page) => {
  const check = (value, message) => { if (!value) throw new Error(message); };
  const origin = await page.evaluate(() => location.origin);
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("console", message => { if (message.type() === "error") errors.push(message.text()); });
  await page.evaluate(() => { localStorage.setItem("rank.modelSetupDismissed", "true"); localStorage.setItem("rank.locale", "zh"); });
  await page.goto(`${origin}/#/deployments`);
  await page.reload();
  const select = async (scope, name, option) => {
    await scope.getByRole("combobox", { name, exact: true }).click();
    await page.getByRole("option", { name: option, exact: typeof option === "string" }).first().click();
  };
  await page.locator(".deployment-list-row").filter({ hasText: "pipeline-e2e" }).click();
  await page.getByRole("heading", { name: "pipeline-e2e", exact: true }).waitFor();
  const navigation = page.locator(".deployment-tabs");
  const dialog = page.getByRole("dialog", { name: "发布新版本", exact: true });
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 900 });
    await page.getByRole("button", { name: "发布新版本", exact: true }).click();
    await dialog.getByRole("button", { name: "开始发布", exact: true }).waitFor();
    check(await dialog.getByLabel("发布前运行回归测试", { exact: true }).isChecked(), "Regression must default on");
    check(await dialog.getByRole("combobox", { name: "发布回归集", exact: true }).innerText().then(v => v.includes("Pipeline pass")), "Agent regression default missing");
    await select(dialog, "发布回归集", /^Pipeline fail/);
    await page.screenshot({ path: `output/playwright/release-review-${width}.png`, fullPage: true });
    await dialog.getByRole("button", { name: "开始发布", exact: true }).click();
    await dialog.locator(".release-task-status[data-status='blocked']").waitFor({ timeout: 20000 });
    await dialog.getByText("发布详情", { exact: true }).click();
    const override = dialog.getByRole("button", { name: "填写原因后继续发布", exact: true });
    check(await override.isDisabled(), "Failed regression override requires a reason");
    await dialog.getByRole("textbox", { name: "继续发布的原因", exact: true }).fill("Browser acceptance failure acknowledged");
    check(await override.isEnabled(), "Reason must enable explicit override");
    await page.screenshot({ path: `output/playwright/release-failed-${width}.png`, fullPage: true });
    await dialog.getByRole("button", { name: "重新确认发布", exact: true }).click();
    await select(dialog, "发布回归集", /^Pipeline pass/);
    await dialog.getByRole("button", { name: "开始发布", exact: true }).click();
    await dialog.locator(".release-task-status[data-status='published']").waitFor({ timeout: 20000 });
    check(await dialog.evaluate(el => { const b = el.getBoundingClientRect(); return b.left >= 0 && b.right <= innerWidth && b.top >= 0 && b.bottom <= innerHeight; }), "Dialog exceeds viewport");
    await page.screenshot({ path: `output/playwright/release-published-${width}.png`, fullPage: true });
    await dialog.getByRole("button", { name: "关闭", exact: true }).click();
    await navigation.getByRole("button", { name: "概览", exact: true }).click();
    check(await page.locator(".route-table").count() === 0, "Deployment still presents separate environments");
    await page.getByRole("heading", { name: "端点策略", exact: true }).waitFor();
    await page.getByRole("button", { name: "接入", exact: true }).click();
    const integration = page.getByRole("dialog", { name: "接入", exact: true });
    await integration.getByRole("button", { name: "复制给 Agent", exact: true }).waitFor();
    await page.context().grantPermissions(["clipboard-read", "clipboard-write"]);
    await integration.getByRole("button", { name: "复制给 Agent", exact: true }).click();
    const instructions = await page.evaluate(() => navigator.clipboard.readText());
    check(instructions.includes("pipeline-e2e") && instructions.includes("RANK_API_KEY") && instructions.includes(".md"), "Integration instructions omit the endpoint or readable documentation");
    const guideURL = instructions.match(/https?:\/\/\S+?\.md/)[0];
    const guide = await page.request.get(guideURL);
    check(guide.ok() && (await guide.text()).includes("previous_response_id"), "Agent cannot read the Markdown reference");
    check(await integration.getByRole("button", { name: "复制可执行命令", exact: true }).isDisabled(), "Commands require a key");
    await integration.getByRole("button", { name: "创建 API Key", exact: true }).click();
    const keyForm = integration.locator(".credential-form");
    const keyName = await keyForm.getByRole("textbox", { name: "名称", exact: true }).inputValue();
    check(/^apikey-\d{8}-\d{6}$/.test(keyName), "Key name is not timestamped");
    check(await keyForm.locator('input[type="checkbox"]').evaluateAll(items => items.every(item => item.checked)), "Permissions must default to all selected");
    await keyForm.getByRole("button", { name: "创建 API Key", exact: true }).click();
    await integration.getByText("API Key 已创建并选中。", { exact: true }).waitFor();
    await integration.getByRole("button", { name: "复制可执行命令", exact: true }).click();
    const command = await page.evaluate(() => navigator.clipboard.readText());
    const secret = command.match(/export RANK_API_KEY='([^']+)'/)[1];
    const response = await page.request.post(origin + "/v1/responses", { headers: { authorization: "Bearer " + secret }, data: { model: "pipeline-e2e", input: "Hello", instructions: "Reply concisely." } });
    check(response.ok(), "Generated key cannot invoke the endpoint");
    await integration.getByRole("button", { name: "复制给 Agent", exact: true }).click();
    check(!(await page.evaluate(() => navigator.clipboard.readText())).includes(secret), "Agent handoff leaked the key");
    check(await page.evaluate(value => !JSON.stringify(localStorage).includes(value) && !JSON.stringify(sessionStorage).includes(value), secret), "Key leaked to browser storage");
    await integration.getByRole("button", { name: "JavaScript", exact: true }).click();
    check(await integration.locator(".integration-code").innerText().then(value => value.includes("previous_response_id") && value.includes('model: "pipeline-e2e"')), "SDK example does not support this deployment and continuation");
    check(await integration.getByRole("link", { name: "完整接入文档", exact: true }).getAttribute("href") === "#/docs?topic=quickstart&endpoint=pipeline-e2e", "Documentation link missing");
    check(await integration.locator(".integration-drawer").evaluate(el => { const r = el.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && r.bottom <= innerHeight; }), "Integration drawer exceeds viewport");
    await page.screenshot({ path: `output/playwright/deployment-integration-${width}.png`, fullPage: true });
    await page.keyboard.press("Escape");
    await integration.waitFor({ state: "hidden" });
    await page.getByRole("button", { name: "接入", exact: true }).click();
    await select(integration, "API Key", new RegExp(keyName));
    check(await integration.getByLabel("API Key 原值", { exact: true }).inputValue() === "", "Closing retained plaintext");
    check(await integration.getByRole("button", { name: "复制可执行命令", exact: true }).isDisabled(), "Existing key was recovered without plaintext");
    await integration.getByLabel("API Key 原值", { exact: true }).fill(secret);
    check(await integration.getByRole("button", { name: "复制可执行命令", exact: true }).isEnabled(), "Retained existing key cannot be reused");
    await page.keyboard.press("Escape");
    await navigation.getByRole("button", { name: "发布记录", exact: true }).click();
    await page.getByRole("heading", { name: "发布检查记录", exact: true }).waitFor();
    check(await page.getByRole("checkbox", { name: "发布检查记录", exact: true }).count() === 0, "Release decisions still require a switch");
    await page.locator(".release-task-history > details").first().waitFor();
    if (!await page.locator(".release-task-history > details").first().evaluate(el => el.open)) await page.locator(".release-task-history > details").first().locator(":scope > summary").click();
    await page.locator(".release-task-history > details").first().locator(".release-task-status[data-status='published']").waitFor();
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Workspace overflows horizontally");
    await page.screenshot({ path: `output/playwright/release-history-${width}.png`, fullPage: true });
  }
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(`${origin}/#/agent`);
  await page.getByRole("region", { name: "最近会话", exact: true }).getByRole("button", { name: "Pipeline conversation", exact: true }).click();
  const card = page.locator(".release-comparison-card");
  await card.getByRole("button", { name: "开始发布", exact: true }).waitFor();
  check(await card.getByLabel("发布前运行回归测试", { exact: true }).isChecked(), "Chat regression default missing");
  await card.getByRole("button", { name: "开始发布", exact: true }).click();
  await card.locator(".release-task-status").waitFor();
  await page.reload();
  await card.locator(".release-task-status[data-status='published']").waitFor({ timeout: 20000 });
  check(await card.getByRole("button", { name: "开始发布", exact: true }).count() === 0, "Reload lost durable release");
  await page.screenshot({ path: "output/playwright/release-conversation-1440.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 900 });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Chat overflows mobile");
  await card.scrollIntoViewIfNeeded();
  await page.screenshot({ path: "output/playwright/release-conversation-390.png", fullPage: true });
  check(errors.length === 0, errors.join("\n"));
  return { viewports: [1440, 390], checks: ["Agent defaults", "dataset replacement", "regression default", "failed regression blocks", "override reason", "retry", "published history", "chat publication", "reload recovery", "viewport fit"], pageErrors: errors };
}
